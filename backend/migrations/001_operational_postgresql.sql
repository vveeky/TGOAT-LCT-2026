-- PostgreSQL 12+ operational schema. Historical Replay and ML feature-state
-- remain in isolated SQLite stores. All timestamps below are instants (UTC).
CREATE TABLE IF NOT EXISTS schema_migrations (
    version INTEGER PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS prediction_history (
    identity TEXT PRIMARY KEY,
    object_id BIGINT NOT NULL,
    snapshot_ts TIMESTAMPTZ NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL,
    risk_probability DOUBLE PRECISION,
    risk_flag BOOLEAN,
    threshold DOUBLE PRECISION,
    prediction_status TEXT NOT NULL,
    degraded_reason TEXT,
    risk_score_kind TEXT NOT NULL,
    model_version TEXT,
    feature_schema_version TEXT,
    reference_snapshot_id TEXT,
    reference_hash TEXT,
    source_freshness_ts TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (object_id, snapshot_ts, model_version)
);
CREATE INDEX IF NOT EXISTS idx_prediction_object_time
    ON prediction_history(object_id, snapshot_ts);

CREATE TABLE IF NOT EXISTS forecast_cards (
    card_id TEXT PRIMARY KEY,
    object_id BIGINT NOT NULL,
    first_positive_snapshot_ts TIMESTAMPTZ NOT NULL,
    last_positive_snapshot_ts TIMESTAMPTZ NOT NULL,
    max_probability DOUBLE PRECISION NOT NULL,
    threshold DOUBLE PRECISION,
    model_version TEXT,
    feature_schema_version TEXT,
    reference_snapshot_id TEXT,
    reference_hash TEXT,
    status TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_cards_object_status
    ON forecast_cards(object_id, status, last_positive_snapshot_ts);

CREATE TABLE IF NOT EXISTS forecast_card_predictions (
    prediction_identity TEXT PRIMARY KEY REFERENCES prediction_history(identity),
    card_id TEXT NOT NULL REFERENCES forecast_cards(card_id)
);

CREATE TABLE IF NOT EXISTS object_workflow_locks (
    object_id BIGINT PRIMARY KEY,
    touched_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS signal_work (
    card_id TEXT PRIMARY KEY REFERENCES forecast_cards(card_id),
    version BIGINT NOT NULL CHECK(version >= 0)
);
CREATE TABLE IF NOT EXISTS signal_decisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id TEXT NOT NULL REFERENCES forecast_cards(card_id),
    object_id BIGINT NOT NULL,
    prediction_identity TEXT NOT NULL REFERENCES prediction_history(identity),
    actor_user_id TEXT NOT NULL,
    actor_role TEXT NOT NULL,
    decision TEXT NOT NULL CHECK(decision IN ('monitoring','false_alarm','inspection_requested')),
    reason_code TEXT,
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    work_version BIGINT NOT NULL,
    command_key TEXT NOT NULL,
    UNIQUE(card_id, work_version)
);
CREATE TABLE IF NOT EXISTS maintenance_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id BIGINT NOT NULL,
    card_id TEXT REFERENCES forecast_cards(card_id),
    prediction_identity TEXT REFERENCES prediction_history(identity),
    decision_id BIGINT UNIQUE REFERENCES signal_decisions(id),
    created_by_user_id TEXT NOT NULL,
    created_by_role TEXT NOT NULL,
    reason TEXT NOT NULL,
    comment TEXT,
    priority TEXT NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('draft','new','assigned','in_progress','awaiting_review','closed','cancelled')),
    origin TEXT NOT NULL CHECK(origin IN ('manual','signal')),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 1,
    command_key TEXT,
    channel_id BIGINT,
    prediction_id BIGINT,
    assignee_user_id TEXT,
    assigned_by_user_id TEXT,
    assigned_at TIMESTAMPTZ,
    started_at TIMESTAMPTZ,
    accepted_by_user_id TEXT,
    accepted_at TIMESTAMPTZ,
    CHECK(origin='manual' OR (card_id IS NOT NULL AND prediction_identity IS NOT NULL
        AND decision_id IS NOT NULL AND status <> 'draft')),
    CHECK(status NOT IN ('assigned','in_progress','awaiting_review') OR assignee_user_id IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_inspection_per_card
    ON maintenance_requests(card_id)
    WHERE origin='signal' AND status IN ('new','assigned','in_progress','awaiting_review');

CREATE TABLE IF NOT EXISTS signal_command_receipts (
    actor_user_id TEXT NOT NULL,
    idempotency_key TEXT NOT NULL,
    card_id TEXT NOT NULL REFERENCES forecast_cards(card_id),
    payload_hash TEXT NOT NULL,
    result_json JSONB NOT NULL,
    work_version BIGINT NOT NULL,
    decision_id BIGINT NOT NULL REFERENCES signal_decisions(id),
    request_id BIGINT REFERENCES maintenance_requests(id),
    committed_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY(actor_user_id, idempotency_key)
);
CREATE TABLE IF NOT EXISTS maintenance_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES maintenance_requests(id),
    technician_user_id TEXT NOT NULL,
    result_code TEXT NOT NULL CHECK(result_code IN ('issue_found','no_issue_found','needs_followup','unable_to_verify')),
    summary TEXT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL,
    revision BIGINT NOT NULL,
    UNIQUE(request_id, revision)
);
CREATE TABLE IF NOT EXISTS maintenance_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES maintenance_requests(id),
    event TEXT NOT NULL,
    actor_user_id TEXT NOT NULL,
    actor_role TEXT NOT NULL,
    "timestamp" TIMESTAMPTZ NOT NULL,
    from_status TEXT,
    to_status TEXT NOT NULL,
    comment TEXT,
    result_id BIGINT REFERENCES maintenance_results(id)
);
CREATE TABLE IF NOT EXISTS maintenance_command_receipts (
    actor_user_id TEXT NOT NULL,
    idempotency_key TEXT NOT NULL,
    request_id BIGINT NOT NULL REFERENCES maintenance_requests(id),
    payload_hash TEXT NOT NULL,
    result_json JSONB NOT NULL,
    committed_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY(actor_user_id,idempotency_key)
);
CREATE TABLE IF NOT EXISTS signal_task_dispositions (
    card_id TEXT PRIMARY KEY REFERENCES forecast_cards(card_id),
    request_id BIGINT NOT NULL REFERENCES maintenance_requests(id),
    state TEXT NOT NULL CHECK(state IN ('new','resolved'))
);

CREATE TABLE IF NOT EXISTS operational_cycles (
    cycle_id TEXT PRIMARY KEY,
    snapshot_ts TIMESTAMPTZ NOT NULL UNIQUE,
    status TEXT NOT NULL,
    object_count BIGINT NOT NULL DEFAULT 0,
    available_count BIGINT NOT NULL DEFAULT 0,
    degraded_count BIGINT NOT NULL DEFAULT 0,
    positive_count BIGINT NOT NULL DEFAULT 0,
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    error TEXT,
    run_mode TEXT NOT NULL DEFAULT 'normal'
);
CREATE TABLE IF NOT EXISTS recommendations (
    recommendation_id TEXT PRIMARY KEY,
    object_id BIGINT NOT NULL,
    snapshot_ts TIMESTAMPTZ NOT NULL,
    card_id TEXT,
    status TEXT NOT NULL,
    code TEXT,
    action TEXT,
    basis_json JSONB NOT NULL,
    rule_version TEXT NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL,
    model_version TEXT,
    reference_hash TEXT,
    UNIQUE(object_id,snapshot_ts,card_id,rule_version)
);
CREATE TABLE IF NOT EXISTS operational_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_identity TEXT NOT NULL UNIQUE REFERENCES prediction_history(identity),
    object_id BIGINT NOT NULL,
    card_id TEXT,
    severity TEXT NOT NULL,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_operational_notifications_object_time
    ON operational_notifications(object_id,created_at DESC);
CREATE TABLE IF NOT EXISTS operational_notification_receipts (
    notification_id BIGINT NOT NULL REFERENCES operational_notifications(id) ON DELETE CASCADE,
    recipient_key TEXT NOT NULL,
    read_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY(notification_id,recipient_key)
);
CREATE TABLE IF NOT EXISTS operational_prediction_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_identity TEXT NOT NULL REFERENCES prediction_history(identity),
    object_id BIGINT NOT NULL,
    snapshot_ts TIMESTAMPTZ NOT NULL,
    actor_user_id TEXT NOT NULL,
    actor_role TEXT NOT NULL,
    decision TEXT NOT NULL,
    reason_code TEXT,
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    idempotency_key TEXT NOT NULL,
    UNIQUE(prediction_identity,actor_user_id,idempotency_key)
);
CREATE INDEX IF NOT EXISTS idx_operational_reviews_identity
    ON operational_prediction_reviews(prediction_identity,created_at);
CREATE TABLE IF NOT EXISTS operational_prediction_outcomes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_identity TEXT NOT NULL REFERENCES prediction_history(identity),
    object_id BIGINT NOT NULL,
    snapshot_ts TIMESTAMPTZ NOT NULL,
    actor_user_id TEXT NOT NULL,
    actor_role TEXT NOT NULL,
    actual_outcome TEXT NOT NULL,
    reason_code TEXT,
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    idempotency_key TEXT NOT NULL,
    UNIQUE(prediction_identity,actor_user_id,idempotency_key)
);
CREATE INDEX IF NOT EXISTS idx_operational_outcomes_identity
    ON operational_prediction_outcomes(prediction_identity,created_at);
