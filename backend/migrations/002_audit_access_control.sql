CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor_user_id TEXT,
    actor_roles TEXT[] NOT NULL DEFAULT '{}',
    actor_scope JSONB NOT NULL DEFAULT '{}'::jsonb,
    request_id TEXT,
    correlation_id TEXT,
    action TEXT NOT NULL,
    resource_type TEXT NOT NULL,
    resource_id TEXT,
    object_id BIGINT,
    previous_state JSONB,
    new_state JSONB,
    outcome TEXT NOT NULL DEFAULT 'success',
    failure_reason TEXT,
    source_mode TEXT NOT NULL DEFAULT 'api',
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    http_method TEXT,
    path TEXT,
    status_code INTEGER,
    role TEXT
);
CREATE INDEX IF NOT EXISTS idx_audit_events_timestamp_id ON audit_events(timestamp DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_audit_events_actor_time ON audit_events(actor_user_id, timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_audit_events_action_time ON audit_events(action, timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_audit_events_resource ON audit_events(resource_type, resource_id, timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_audit_events_object_time ON audit_events(object_id, timestamp DESC);

CREATE OR REPLACE FUNCTION reject_audit_event_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_events is append-only';
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS audit_events_append_only ON audit_events;
CREATE TRIGGER audit_events_append_only
    BEFORE UPDATE OR DELETE ON audit_events
    FOR EACH ROW EXECUTE FUNCTION reject_audit_event_mutation();

CREATE TABLE IF NOT EXISTS access_assignments (
    user_id TEXT PRIMARY KEY,
    roles TEXT[] NOT NULL DEFAULT '{}',
    grants TEXT[] NOT NULL DEFAULT '{}',
    groups TEXT[] NOT NULL DEFAULT '{}',
    scope_roots BIGINT[] NOT NULL DEFAULT '{}',
    version BIGINT NOT NULL DEFAULT 1 CHECK (version >= 1),
    updated_by_user_id TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS revoked_auth_tokens (
    token_id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_revoked_auth_tokens_expiry ON revoked_auth_tokens(expires_at);
